-- ----------------------------------------------------------------------------
-- Status / audit history — requirement #18. Generic table covering every
-- entity that has a status field (inquiries, bookings, lrs where relevant).
-- Written by the sync layer, not by the app directly, so a generated id here
-- is fine.
-- ----------------------------------------------------------------------------
create table bgts_os.status_history (
  id               text primary key default gen_random_uuid()::text,
  entity_type      text not null check (entity_type in ('inquiry', 'booking', 'invoice', 'bank_txn')),
  entity_id        text not null,
  previous_status  text,
  new_status       text not null,
  changed_by       uuid references auth.users (id), -- real Supabase Auth user id — unrelated to the app-id correction above
  changed_at       timestamptz not null default now(),
  comment          text
);
create index idx_status_history_entity on bgts_os.status_history (entity_type, entity_id, changed_at desc);

-- ----------------------------------------------------------------------------
-- App users / profile — created because this rollout adds Supabase Auth
-- (email/password) as the minimum viable login gate; every authenticated
-- user is currently treated as one shared company account (see 0003_rls.sql),
-- not per-record ownership — the app itself has no roles/permissions model
-- today, so this profile table exists mainly to give status_history.changed_by
-- a friendly name to show, and as the place to add real roles later. id is a
-- real Supabase Auth user id (uuid) — unrelated to the app-id correction above.
-- ----------------------------------------------------------------------------
create table bgts_os.app_users (
  id          uuid primary key references auth.users (id) on delete cascade,
  name        text not null default '',
  email       text not null default '',
  role        text not null default 'admin',
  created_at  timestamptz not null default now()
);
