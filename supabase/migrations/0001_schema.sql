-- ============================================================================
-- BGTS-OS database schema — migration 0001  (v2 — corrected ID type, see note)
-- ============================================================================
-- Everything for this app lives in its own Postgres schema, "bgts_os", so it
-- can share the same Supabase project as your existing BGTS website without
-- any risk of table-name collisions with whatever that site already uses in
-- "public". Run this file (and 0002_functions.sql, 0003_rls.sql after it) in
-- the Supabase SQL Editor of your EXISTING project — nothing here creates a
-- new project or touches any table outside this schema.
--
-- CORRECTION FROM THE FIRST VERSION OF THIS FILE: every table below used a
-- `uuid` primary key generated by the database. That's wrong for this app —
-- the existing screens generate their own ids client-side via uid() in
-- src/logic.js (e.g. "lr1a2b3c4d"), and every single one of the ~20 screens
-- calls that function directly when creating a record. Keeping the database
-- in charge of id generation would mean either rewriting every create-action
-- in every screen (exactly what you said not to do) or living with two
-- different, disconnected id schemes. So every id column here is `text`,
-- supplied by the app exactly as it is today — the database's job is to
-- store and constrain those ids (uniqueness, foreign keys), not generate
-- new ones. If you already ran the first version of this file, drop the
-- schema and re-run this corrected version — see the note at the very top
-- of the SQL Editor instructions you were given.
--
-- This schema is a 1:1 mapping of the app's current data model as it exists
-- today in src/logic.js's blankDB()/blankLR()/blankInquiry() and every screen
-- that creates records — no invented fields, no invented "Quote" entity (the
-- app has none), no renamed statuses. Every enum CHECK constraint below uses
-- the exact string values already used in the app so existing UI code needs
-- no relabeling.
-- ============================================================================

create schema if not exists bgts_os;
set search_path = bgts_os, public;

-- A handful of child-table rows have no id in the app's own data model at all
-- (LR goods rows, LR expense lines, contract rate lines, legacy billing-
-- backup lines/bills — see blankLR().goods, contract.rates, etc. in
-- src/logic.js, none of which carry an id field). Those get a
-- database-generated surrogate key (still stored as text, for consistency
-- with every other id in this schema) since nothing in the app needs to
-- reference them individually. gen_random_uuid() is built into Postgres core
-- on 13+, which is what every current Supabase project runs — no extension
-- needed.

