  amount        numeric not null default 0,
  paid_through  text not null default '' check (paid_through in
                  ('', 'Bank — Current A/c', 'Petty Cash', 'UPI', 'Credit (payable)')),
  vendor        text not null default '',
  ref           text not null default '',
  notes         text not null default '',
  src           text not null default 'manual' check (src in ('manual', 'lr', 'hire')),
  created_at    timestamptz not null default now()
);
create index idx_acct_expenses_lr on bgts_os.acct_expenses (lr_id);
create index idx_acct_expenses_branch on bgts_os.acct_expenses (branch_id);
create index idx_acct_expenses_date on bgts_os.acct_expenses (date desc);

